#!/usr/bin/env node
/**
 * Static portability gate.
 *
 * "Migrate to another machine" fails at the first absolute path a script
 * assumes. This check reads the *code* trees (not prose) and reports machine
 * bindings, so the migration checklist cannot silently rot.
 *
 * A baseline file records the violations that already exist. New ones fail the
 * gate; known ones are reported as a shrinking count, never silently ignored.
 *
 * Run:  node scripts/verify-portable.js
 *       node scripts/verify-portable.js --write-baseline
 *       node scripts/verify-portable.js --list
 */

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "..");
const BASELINE_FILE = path.join(REPO_ROOT, "scripts", "portable-baseline.json");

/** Trees that execute on the operator's machine. */
const SCAN_DIRS = ["bin", "dsh-plugins", "scripts", "src", "tools"];

const SCAN_EXTENSIONS = new Set([
  ".js", ".mjs", ".cjs", ".ts", ".py", ".ps1", ".vbs", ".cmd", ".bat", ".yml", ".yaml", ".json",
]);

const SKIP_DIRS = new Set([
  "node_modules", ".git", "tmp", ".venv", ".venv-akasha", "analysis", "user", "output", "outputs",
]);

/** Files whose whole job is to be a template a human edits per machine. */
const ALLOWED_FILES = new Set([]);

const PATTERNS = [
  { name: "windows-drive-path", re: /\b[A-Za-z]:[\\/](?![\\/])/ },
  { name: "user-home-path", re: /\bUsers[\\/][A-Za-z0-9._-]+/ },
  { name: "posix-home-path", re: /\/Users\/[A-Za-z0-9._-]+|\/home\/[A-Za-z0-9._-]+/ },
];

/** Lines that legitimately mention a drive path (comments, usage strings, and
 *  this checker's own JSON, which quotes offending lines verbatim). */
const LINE_ALLOW = [
  /^\s*(\/\/|#|\*)/,
  /--help|usage:/i,
  /^\s*"(text|key|note)":/,
];

function walk(dir, out = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) {
        continue;
      }
      walk(full, out);
    } else if (entry.isFile() && SCAN_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      out.push(full);
    }
  }
  return out;
}

function collectViolations() {
  const violations = [];
  let scanned = 0;
  for (const relDir of SCAN_DIRS) {
    const absDir = path.join(REPO_ROOT, relDir);
    if (!fs.existsSync(absDir)) {
      continue;
    }
    for (const file of walk(absDir)) {
      const rel = path.relative(REPO_ROOT, file).split(path.sep).join("/");
      if (ALLOWED_FILES.has(rel)) {
        continue;
      }
      scanned += 1;
      const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
      for (let index = 0; index < lines.length; index += 1) {
        const line = lines[index];
        if (LINE_ALLOW.some((re) => re.test(line))) {
          continue;
        }
        for (const pattern of PATTERNS) {
          const match = line.match(pattern.re);
          if (!match) {
            continue;
          }
          violations.push({
            rel,
            line: index + 1,
            rule: pattern.name,
            text: line.trim().slice(0, 120),
            hit: match[0],
          });
          break;
        }
      }
    }
  }
  return { violations, scanned };
}

/** Identity that survives line shifts: file + normalised source text. */
function violationKey(violation) {
  const digest = crypto.createHash("sha1").update(`${violation.rel}\n${violation.text}`).digest("hex").slice(0, 12);
  return `${violation.rel}#${digest}`;
}

function loadBaseline() {
  if (!fs.existsSync(BASELINE_FILE)) {
    return { entries: [] };
  }
  try {
    return JSON.parse(fs.readFileSync(BASELINE_FILE, "utf8"));
  } catch {
    return { entries: [] };
  }
}

function writeBaseline(violations) {
  const entries = violations
    .map((violation) => ({ key: violationKey(violation), rel: violation.rel, line: violation.line, rule: violation.rule, text: violation.text }))
    .sort((a, b) => (a.key < b.key ? -1 : 1));
  const payload = {
    note: "Known machine bindings. Generated by scripts/verify-portable.js --write-baseline; shrink it, never grow it silently.",
    count: entries.length,
    entries,
  };
  fs.writeFileSync(BASELINE_FILE, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
  console.log(`baseline written: ${entries.length} entr(y|ies) -> ${path.relative(REPO_ROOT, BASELINE_FILE)}`);
}

function main() {
  const argv = process.argv.slice(2);
  const { violations, scanned } = collectViolations();

  if (argv.includes("--write-baseline")) {
    writeBaseline(violations);
    return 0;
  }

  const baseline = loadBaseline();
  const known = new Set((baseline.entries || []).map((entry) => entry.key));
  const isKnown = (violation) => known.has(violationKey(violation));
  const fresh = violations.filter((violation) => !isKnown(violation));
  const stillPresent = new Set(violations.map(violationKey));
  const fixed = (baseline.entries || []).filter((entry) => !stillPresent.has(entry.key));

  if (argv.includes("--list")) {
    for (const violation of violations) {
      console.log(`${isKnown(violation) ? "known" : "NEW  "} ${violation.rel}:${violation.line} [${violation.rule}] ${violation.text}`);
    }
  }

  console.log(`scanned ${scanned} file(s): ${violations.length} machine path(s), ${fresh.length} new, ${fixed.length} fixed since baseline`);

  if (fresh.length) {
    const byFile = new Map();
    for (const violation of fresh) {
      if (!byFile.has(violation.rel)) {
        byFile.set(violation.rel, []);
      }
      byFile.get(violation.rel).push(violation);
    }
    for (const [rel, items] of [...byFile.entries()].sort()) {
      console.error(`${rel} — ${items.length} new machine path(s)`);
      for (const item of items.slice(0, 6)) {
        console.error(`  ${item.line}: [${item.rule}] ${item.text}`);
      }
      if (items.length > 6) {
        console.error(`  … ${items.length - 6} more`);
      }
    }
    console.error("portable check failed: new machine bindings appeared");
    console.error("Rule: code derives machine paths from env or from its own location, never from a literal.");
    return 1;
  }

  if (fixed.length) {
    console.log(`portable improved: ${fixed.length} baseline entr(y|ies) no longer present — run --write-baseline to shrink it`);
    for (const entry of fixed.slice(0, 8)) {
      console.log(`  fixed ${entry.rel}:${entry.line}`);
    }
  }
  return 0;
}

if (require.main === module) {
  process.exitCode = main();
}

module.exports = { main, collectViolations, violationKey, SCAN_DIRS, BASELINE_FILE };
